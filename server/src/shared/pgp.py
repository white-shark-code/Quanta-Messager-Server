"""Async wrapper around python-gnupg for OpenPGP operations.

Uses RFC 9580-compliant GnuPG (>=2.4) instead of pgpy 0.6 which is
stuck at RFC 4880 and cannot parse BLAKE2b / SHA3 keys generated by
modern OpenPGP clients (e.g., openpgp.js v6).

Provides:
- ``GnupgBackend.import_key(data) -> (fingerprint, is_private)``
- ``GnupgBackend.verify(msg, sig, pubkey) -> bool``
- ``GnupgBackend.delete_key(fingerprint) -> None``

All GPG subprocess calls are wrapped with ``asyncio.to_thread`` so
they do not block the FastAPI event loop.

Обёртка над python-gnupg с поддержкой RFC 9580 через GnuPG 2.4+.
"""

import asyncio
import os
import tempfile
from functools import partial
from pathlib import Path

import gnupg
from fastapi import HTTPException, status


class GnupgBackend:
    """Async-friendly GnuPG backend with isolated per-process homedir.

    The homedir is created on first instantiation and reused for the
    lifetime of the process. Imported keys are deleted immediately
    after use to avoid leaking fingerprints between requests.

    Гомедир создаётся при первом обращении; импортированные ключи
    удаляются после использования для изоляции запросов.
    """

    def __init__(self, homedir: Path | None = None) -> None:
        if homedir is None:
            homedir = Path(tempfile.gettempdir()) / f"quant-gpg-{os.getpid()}"
        homedir.mkdir(parents=True, exist_ok=True)
        os.chmod(homedir, 0o700)
        self.homedir = homedir
        self.gpg = gnupg.GPG(gnupghome=str(homedir))

    async def import_key(self, data: bytes) -> tuple[str | None, bool]:
        """Import ASCII-armored PGP key into a temporary keyring.

        Args:
            data: ASCII-armored PGP key material (public or private).

        Returns:
            Tuple ``(fingerprint, is_private)``. ``fingerprint`` is
            ``None`` if the import failed.

        Импортирует ASCII-armored PGP-ключ во временный keyring.
        Возвращает ``(fingerprint, is_private)``.
        """
        loop = asyncio.get_running_loop()
        return await loop.run_in_executor(None, self._import_key_sync, data)

    def _import_key_sync(self, data: bytes) -> tuple[str | None, bool]:
        text = data.decode("utf-8", errors="replace")
        result = self.gpg.import_keys(text)
        if not result.fingerprints:
            return None, False
        fingerprint = result.fingerprints[0]
        # python-gnupg 0.5.6 doesn't expose ``sec_fingerprints`` —
        # ``sec_imported`` is the count of secret keys re-imported.
        is_private = getattr(result, "sec_imported", 0) and result.sec_imported > 0
        return fingerprint, is_private

    async def delete_key(self, fingerprint: str) -> None:
        """Remove a previously imported key from the keyring."""
        loop = asyncio.get_running_loop()
        await loop.run_in_executor(
            None, partial(self.gpg.delete_keys, fingerprint)
        )

    async def verify(
        self, msg: bytes, sig: bytes, pubkey: bytes
    ) -> tuple[bool, str]:
        """Verify detached PGP signature using ``gpg --verify``.

        Imports the public key into a temporary keyring, runs verify,
        then deletes the key to avoid leaking fingerprints.

        Args:
            msg: Original message bytes (the data being signed).
            sig: Detached signature bytes.
            pubkey: ASCII-armored public key bytes.

        Returns:
            Tuple ``(is_valid, stderr_text)``. ``is_valid`` is ``True``
            only when GnuPG confirms a valid signature.

        Выполняет ``gpg --verify`` для отделённой подписи.
        """
        loop = asyncio.get_running_loop()
        return await loop.run_in_executor(
            None, self._verify_sync, msg, sig, pubkey
        )

    def _verify_sync(
        self, msg: bytes, sig: bytes, pubkey: bytes
    ) -> tuple[bool, str]:
        text = pubkey.decode("utf-8", errors="replace")
        result = self.gpg.import_keys(text)
        if not result.fingerprints:
            return False, "failed to import public key"
        fingerprint = result.fingerprints[0]
        sig_path = None
        try:
            with tempfile.NamedTemporaryFile(
                suffix=".sig", delete=False, dir=self.homedir
            ) as sf:
                sf.write(sig)
                sig_path = sf.name
            # verify_data reads data from memory and signature from file
            verified = self.gpg.verify_data(sig_path, msg)
            stderr = getattr(verified, "stderr", "") or ""
            return bool(verified.valid), stderr
        finally:
            if sig_path and os.path.exists(sig_path):
                try:
                    os.unlink(sig_path)
                except OSError:  # pragma: no cover
                    pass
            try:
                self.gpg.delete_keys(fingerprint)
            except Exception:  # pragma: no cover
                pass


_backend: GnupgBackend | None = None


def get_backend() -> GnupgBackend:
    """Return the process-wide GnuPG backend, lazy-initialized.

    Возвращает singleton-объект ``GnupgBackend``, инициализируемый
    при первом обращении.
    """
    global _backend
    if _backend is None:
        _backend = GnupgBackend()
    return _backend


def is_encrypted_pgp_message(blob: bytes) -> bool:
    """Heuristic check for an OpenPGP-encrypted message blob.

    Inspects the ASCII-armor header. Adequate for the client contract
    where the frontend always produces ``-----BEGIN PGP MESSAGE-----``
    blocks for encrypted payloads.

    Простая проверка заголовка ASCII-armor: для дешифруемых
    сообщений клиент всегда посылает именно такой блок.
    """
    return b"-----BEGIN PGP MESSAGE-----" in blob


def raise_invalid_signature(detail: str) -> None:
    """Helper to raise a 422 with the canonical detail string.

    Вспомогательная функция для единых строк ошибок.
    """
    raise HTTPException(
        status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
        detail=detail,
    )
